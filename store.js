async function handleEditStore(sock, jid, msg, parts, db, saveDb, cleanSender, isBotOwner, isEmperor) {
    try {
        if (!isBotOwner && !isEmperor) {
            await safeSend(sock, jid, {
                text: "⛔ هذا الأمر للمطور أو الإمبراطور فقط."
            }, { quoted: msg });
            return true;
        }

        const customMessage = parts.join(" ").trim();

        if (!customMessage) {
            // عرض الرسالة الحالية
            const current = db.storeCustomMessage || "لا توجد رسالة مخصصة";
            await safeSend(sock, jid, {
                text: `📝 الرسالة المخصصة الحالية:\n\n${current}\n\nلتعديلها: .تعديل متجر [الرسالة]`
            }, { quoted: msg });
            return true;
        }

        db.storeCustomMessage = customMessage;
        if (typeof saveDb === "function") saveDb();

        await safeSend(sock, jid, {
            text: `✅ تم حفظ قائمة المتجر رقم 2`
        }, { quoted: msg });

        return true;

    } catch (error) {
        console.error("❌ خطأ في handleEditStore:", error?.message || error);
        return false;
    }
}

