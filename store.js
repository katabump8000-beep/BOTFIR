async function handleStoreCommand(sock, jid, msg, db, cleanSender) {
    try {
        // التحقق من أن القروب هو قروب البنك
        const isBankGroup = db.bankGroups && db.bankGroups[jid] === true;

        if (!isBankGroup) {
            await safeSend(sock, jid, {
                text: `❆━━━━━═⏣⊰⚠️⊱⏣═━━━━━❆
  *هذا الأمر يعمل فقط في*
  *قروب البنك*
❆━━━━━═⏣⊰⚠️⊱⏣═━━━━━❆`
            }, { quoted: msg });
            return true;
        }

        const nickname = getUserNickname(db, cleanSender);

        // إرسال رسالة الترحيب
        await safeSend(sock, jid, {
            text: getStoreWelcomeMessage(nickname),
            mentions: [`${cleanSender}@s.whatsapp.net`]
        }, { quoted: msg });

        // إرسال قائمة المتجر
        await safeSend(sock, jid, {
            text: getStoreListMessage()
        });

        // إرسال الرسالة المخصصة (إذا وجدت)
        if (db.storeCustomMessage && String(db.storeCustomMessage).trim()) {
            await safeSend(sock, jid, {
                text: db.storeCustomMessage
            });
        }

        return true;

    } catch (error) {
        console.error("❌ خطأ في handleStoreCommand:", error?.message || error);
        return false;
    }
}

