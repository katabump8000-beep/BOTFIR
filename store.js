// ============================================================

function getRandomPrice(itemName) {
    const prices = STORE_PRICES[itemName];
    if (!prices || prices.length === 0) return 0;

    // ترتيب الأسعار تصاعدياً
    const sorted = [...prices].sort((a, b) => a - b);
    const lowest = sorted[0];
    const middle = sorted[1];
    const highest = sorted[2];

    // احتمالات: 
    // - أقل سعر: 50%
    // - سعر متوسط: 35%
    // - أعلى سعر: 15% (تم تقليله بنسبة 65% تقريباً)
    const rand = Math.random() * 100;

    if (rand < 50) {
        return lowest;
    } else if (rand < 85) {
        return middle;
    } else {
        return highest;
    }
}

